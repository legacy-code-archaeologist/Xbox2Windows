"""Compare native and translated FSQRT of the x87 leaf-function profile.

Usage:
    python tests/cpu/x87_sqrt.py asm <asm> <def>             regenerate the MASM source and exports
    python tests/cpu/x87_sqrt.py emit <dll> <cpp> [control]   translate (and optionally mutate) the fixture
    python tests/cpu/x87_sqrt.py check <harness> <native> <lifted> [controls...]

The exports, harness and guards follow tests/cpu/x87_add.py, and the other steps use the format of
tests/cpu/x87_moves.py. emit checks that every decoded x87 instruction is the form its sequence names.
The model rounds an integer square root with Python integers and Fraction and is independent of
tools/x87_soft.h.
"""
from fractions import Fraction
from math import isqrt
from pathlib import Path
import platform
import random
import re
import sys

sys.path.insert(0, str(Path(__file__).resolve().parents[2] / "tools"))
import x87_add as base  # noqa: E402  (tests/cpu is the script directory)
import x87_moves as moves  # noqa: E402
from x87_add import (INDEFINITE, J, Q, classify, floor_log2, from_binary, m80_bytes, m80_exact,  # noqa: E402
                     round_format, to_binary)
from x87_div import SIZE  # noqa: E402
from x87_mul import mul  # noqa: E402

INPUT, OUTPUT = base.INPUT, base.OUTPUT

P80 = [("fld", "m80", 0), ("fld", "m80", 16)]
# ("fsqrt",) is the new step; the others use the x87_moves format.
SEQUENCES = {
    "sqrt_m80": ("m80", [("fld", "m80", 0), ("fsqrt",), ("fstp", "m80", 0)]),
    "sqrt_to_m64": ("m80", [("fld", "m80", 0), ("fsqrt",), ("fstp", "m64", 0)]),
    "sqrt_to_m32": ("m80", [("fld", "m80", 0), ("fsqrt",), ("fstp", "m32", 0)]),
    "sqrt_twice": ("m80", [("fld", "m80", 0), ("fsqrt",), ("fsqrt",), ("fstp", "m80", 0)]),
    "sqrt_f64": ("f64", [("fld", "m64", 0), ("fsqrt",), ("fstp", "m64", 0)]),
    "sqrt_f32": ("f32", [("fld", "m32", 0), ("fsqrt",), ("fstp", "m32", 0)]),
    # The root of ST(0) with a second value below it: sqrt(b) + a, and sqrt(a * a + b * b).
    "sqrt_add": ("pair80", P80 + [("fsqrt",), ("faddp", "pop", 1), ("fstp", "m80", 0)]),
    "sqrt_sum_squares": ("pair80", [("fld", "m80", 0), ("fld_st", 0), ("fmulp", "pop", 1), ("fld", "m80", 16),
                                    ("fld_st", 0), ("fmulp", "pop", 1), ("faddp", "pop", 1), ("fsqrt",),
                                    ("fstp", "m80", 0)]),
    "sqrt_depth8": ("m64x8", [("fld", "m64", 8 * k) for k in range(8)] + [("fsqrt",)]
                    + [("fstp", "m64", 8 * k) for k in range(8)]),
}

CONTROLS = {
    # The root rounds to 64 significand bits.
    "pc64": (re.compile(r"x87_format\(cw\), x87_rounding\(cw\)\);  // sqrt round"),
             "X87Format{64, 16383, 0x7ffe}, x87_rounding(cw));  // sqrt round"),
    # The root rounds in the binary64 exponent range.
    "double": (re.compile(r"x87_format\(cw\), x87_rounding\(cw\)\);  // sqrt round"),
               "x87_f64, x87_rounding(cw));  // sqrt round"),
    # The remainder is ignored.
    "nosticky": (re.compile(r"const uint64_t sticky = [^;]*;  // sqrt sticky"), "const uint64_t sticky = 0;  // sqrt sticky"),
    # sqrt(-0) gives +0.
    "negzero": (re.compile(r"if \(x87_is_zero\(a\)\) return a;\r?\n    if \(x87_sign\(a\)\)"),
                "if (x87_is_zero(a)) return {0, 0};\n    if (x87_sign(a))"),
    # A negative operand gives the root of its magnitude.
    "negabs": (re.compile(r"if \(x87_sign\(a\)\) return x87_indefinite;"), "a.se &= 0x7fff;"),
    # A signaling NaN is returned unquieted.
    "snan": (re.compile(r"if \(x87_is_nan\(a\)\) return x87_quiet\(a\);"), "if (x87_is_nan(a)) return a;"),
}


# ---- MASM generation and decoding ------------------------------------------------------------------

def asm_line(step):
    return "    fsqrt" if step[0] == "fsqrt" else moves.asm_line(step)


def expected_form(step):
    return ("fsqrt", "") if step[0] == "fsqrt" else moves.expected_form(step)


def write_asm(asm_path, def_path):
    lines = ["; coverage: source cpu_aot_x87_sqrt",
             "; Generated by tests/cpu/x87_sqrt.py asm; edit SEQUENCES there and regenerate.",
             "; Source-owned differential fixture for FSQRT in the x87 leaf-function profile. Each export reads",
             "; an input block at RCX, writes an output block at RDX and returns with the x87 stack empty.",
             ".code", ""]
    for name, (_, steps) in SEQUENCES.items():
        lines += [f"{name} PROC FRAME", "    .endprolog", *(asm_line(s) for s in steps), "    ret", f"{name} ENDP", ""]
    lines.append("END")
    Path(asm_path).write_text("\n".join(lines) + "\n", encoding="ascii")
    Path(def_path).write_text("EXPORTS\n" + "".join(f"    {name}\n" for name in SEQUENCES), encoding="ascii")


def emit(image, output, control="lifted"):
    import pefile
    from cpu_leaf_aot import export_rva
    from cpu_ranges import function_ranges
    from ffx_version_query import INTEGER_HEADER, lower, region
    from x87_lower import X87_HEADER, is_x87

    parts = [INTEGER_HEADER, X87_HEADER]
    with pefile.PE(str(image), fast_load=True) as pe:
        for name, (_, steps) in SEQUENCES.items():
            (bounds,) = function_ranges(pe, export_rva(pe, name))
            body = region(pe, *bounds)
            decoded = [moves.decoded_form(i) for i in body if is_x87(i)]
            wanted = [expected_form(s) for s in steps]
            if decoded != wanted:
                raise AssertionError(f"{name} assembled as {decoded}, expected {wanted}")
            code = lower(body, ["rcx = a; rdx = b;"], {}, {}, {}, x87=True)
            parts.append(f'extern "C" __declspec(dllexport) word {name}(word a, word b) {{\n{code}\n}}\n')
    text = "".join(parts)
    if control != "lifted":
        expression, replacement = CONTROLS[control]
        text, count = expression.subn(replacement, text)
        if not count:
            raise AssertionError(f"control {control} changed nothing")
        print(f"control {control}: {count} replacements")
    output.write_text(text, encoding="ascii")


# ---- Independent model -----------------------------------------------------------------------------

EXTRA = 160  # bits of the integer root; far more than the 53 bits it rounds to


def sqrt(v):
    """FSQRT with control word 0x027F."""
    c = classify(v)
    if c[0] == "unsupported":
        return INDEFINITE
    if c[0] == "nan":
        return v[0] | Q, v[1]
    if c[0] == "zero":
        return v
    if c[1]:
        return INDEFINITE
    if c[0] == "inf":
        return v
    q = c[2]
    # Scale so that the integer root has about EXTRA bits whatever the magnitude: root = isqrt(floor(s))
    # with s = q * 4^k. When s is not a perfect square, sqrt(s) lies strictly between root and root + 1,
    # and the midpoint of that interval rounds the same way at 53 bits.
    k = EXTRA - floor_log2(q) // 2
    scaled = q * Fraction(4) ** k
    n = scaled.numerator // scaled.denominator
    root = isqrt(n)
    exact = root * root == n and scaled.denominator == 1
    unit = Fraction(2) ** -k
    value = root * unit if exact else (2 * root + 1) * unit / 2
    m, biased = round_format(value, 53, 16383, 0x7FFE)
    return m << 11, biased


def reference(name, data):
    slots, out = [], bytearray(b"\xcc" * OUTPUT)

    def read(kind, offset):
        return int.from_bytes(data[offset:offset + SIZE[kind]], "little")

    for op, *args in SEQUENCES[name][1]:
        if op == "fsqrt":
            slots[-1] = sqrt(slots[-1])
        elif op == "fld":
            raw = read(*args)
            slots.append((raw & (2 ** 64 - 1), raw >> 64) if args[0] == "m80" else from_binary(args[0], raw))
        elif op == "fstp":
            kind, offset = args
            v = slots.pop()
            encoded = v[0] | v[1] << 64 if kind == "m80" else to_binary(kind, v)
            out[offset:offset + SIZE[kind]] = encoded.to_bytes(SIZE[kind], "little")
        elif op == "fld_st":
            slots.append(slots[-1 - args[0]])
        else:  # ("faddp" | "fmulp", "pop", 1)
            slots[-2] = (base.add if op == "faddp" else mul)(slots[-2], slots[-1])
            slots.pop()
    assert not slots
    return bytes(out)


# ---- Inputs ----------------------------------------------------------------------------------------

def m80_inputs(rng):
    values = list(base.m80_singles())
    for _ in range(300):  # perfect squares: exact roots of up to 32 bits, at even and odd exponents
        k = rng.getrandbits(rng.randint(1, 32)) | 1
        values.append(m80_exact(0, Fraction(k * k) * Fraction(2) ** rng.randint(-200, 200)))
    for _ in range(600):  # m * m rounded to 64 bits, for m halfway between two 53-bit neighbours
        m = (rng.getrandbits(52) | 1 << 52) * 2 + 1                        # 54 bits ending in 1
        square = m * m
        shift = square.bit_length() - 64
        sig = min((square >> shift) + rng.choice((-1, 0, 0, 1)), 2 ** 64 - 1)
        # sig * 2^(shift + 2j) is close to (m * 2^j)^2, so its root lies next to a 53-bit tie.
        j = rng.randint(-4000, 4000)
        values.append((sig, 16383 + 63 + shift + 2 * j))
    for _ in range(50):  # signaling NaNs of both signs
        values.append((J | 1 + rng.getrandbits(61), 0x7FFF | rng.choice((0, 0x8000))))
    for _ in range(400):  # random values over most of the extended exponent range, and denormals
        values.append((J | rng.getrandbits(63), rng.randint(1, 0x7FFE)))
        values.append((rng.getrandbits(63), 0))
    return values


def cases():
    rng = random.Random(53)
    m80 = m80_inputs(rng)
    f64 = base.f64_bits() + [rng.getrandbits(63) for _ in range(200)]
    f32 = base.f32_bits() + [rng.getrandbits(31) for _ in range(200)]
    blocks = {
        "m80": [m80_bytes(v) for v in m80],
        "f64": [b.to_bytes(8, "little") for b in f64],
        "f32": [b.to_bytes(4, "little") for b in f32],
        "pair80": [m80_bytes(a) + m80_bytes(b) for a, b in zip(m80, reversed(m80))],
        "m64x8": [b"".join(rng.choice(f64).to_bytes(8, "little") for _ in range(8)) for _ in range(300)],
    }
    for name, (kind, _) in SEQUENCES.items():
        for block in blocks[kind]:
            yield name, block.ljust(INPUT, b"\0")


# ---- Check -----------------------------------------------------------------------------------------

def check(harness_path, native_path, lifted_path, *control_paths):
    expected = [(name, data, reference(name, data)) for name, data in cases()]
    for label, path in (("native", native_path), ("lifted", lifted_path)):
        run = base.Runner(harness_path, path)
        bad = 0
        for name, data, want in expected:
            got, state = run(name, data)
            if not base.entry_state_ok(state):
                raise AssertionError(f"{label} {name} left state {state:#014x}; the profile requires control "
                                     "0x027f and an empty stack at TOP 0")
            if got != want:
                if not bad:
                    print(f"{label} first mismatch: {name}(input {data[:48].hex()})\n  got      {got[:48].hex()}\n"
                          f"  expected {want[:48].hex()}")
                bad += 1
        if bad:
            raise AssertionError(f"{label}: {bad}/{len(expected)} mismatches")
    print(f"{len(expected)} cases over {len(SEQUENCES)} exports (output block and guards) matched the reference "
          "in native and translated DLLs; each export returned with control 0x027f and an empty stack")
    print(f"processor: {platform.processor()}")
    first = {}
    for name, data, want in expected:
        first.setdefault(name, (data, want))
    for label, path in (("native", native_path), ("lifted", lifted_path)):
        run = base.Runner(harness_path, path)
        failed = [name for name, (data, want) in first.items() if not base.preserved(run, "x87_call", name, data, want)]
        if failed:
            raise AssertionError(f"x87_call lost a live caller value or control word around {label} {failed}")
    print(f"x87_call kept a live caller ST(0) value and control word around all {len(first)} native and "
          "translated exports")
    for path in control_paths:
        control = Path(path).stem.rsplit("_", 1)[-1]
        run = base.Runner(harness_path, path)
        bad = sum(1 for name, data, want in expected if run(name, data)[0] != want)
        print(f"control {control}: {bad}/{len(expected)} mismatches")
        if not bad:
            raise AssertionError(f"control {control} matched every case")
    check_rejections()


def check_rejections():
    from iced_x86 import Decoder
    from ffx_version_query import lower

    def attempt(hex_bytes):
        body = list(Decoder(64, bytes.fromhex(hex_bytes), ip=0x1000))
        try:
            lower(body, [], {}, {}, {}, x87=True)
        except ValueError as exc:
            return str(exc)
        return None

    fld, fstp = "db 29", "db 3a"  # fld tbyte ptr [rcx]; fstp tbyte ptr [rdx]
    rejected = {
        "fsqrt on an empty stack": (attempt("d9 fa c3"), "x87 stack underflow"),
        "fsqrt without a store": (attempt(f"{fld} d9 fa c3"), "x87 stack not empty at return"),
        "f2xm1": (attempt(f"{fld} d9 f0 {fstp} c3"), "unsupported x87 operation"),
        "fyl2x": (attempt(f"{fld} d9 f1 {fstp} {fstp} c3"), "unsupported x87 operation"),
        "fnsave": (attempt(f"{fld} dd 31 {fstp} c3"), "unsupported x87 operation"),
        "frstor": (attempt(f"dd 21 {fld} {fstp} c3"), "unsupported x87 operation"),
    }
    for case, (message, needle) in rejected.items():
        if message is None or needle not in message:
            raise AssertionError(f"{case}: expected a rejection containing {needle!r}, got {message!r}")
    print(f"rejected {len(rejected)} sequences outside the profile: " + "; ".join(rejected))


if __name__ == "__main__":
    mode, first, second, *rest = sys.argv[1:]
    if mode == "asm":
        write_asm(first, second)
    elif mode == "emit":
        emit(Path(first), Path(second), *rest)
    elif mode == "check":
        check(first, second, *rest)
    else:
        raise ValueError(mode)
